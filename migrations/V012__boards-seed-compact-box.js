/**
 * V012 — a boards script V011 left at the store root says `compact` the way schema V005 does.
 *
 *     ..., on_success_mode, rank) VALUES              ..., on_success_mode, on_success_compact, rank) VALUES
 *     ..., 'compact', 'i');                    →      ..., 'continue', true, 'i');
 *     ..., 'end', 'r');                               ..., 'end', false, 'r');
 *
 * Schema V005 of workflows-service split `on_success_mode = 'compact'` into two answers — the mode
 * `continue` and the box `on_success_compact` — and narrowed the column's check to the two words
 * left. A script V011 wrote before that still inserts `'compact'`, and PostgreSQL refuses it: the
 * import is one transaction, so a board with one such card imports nothing at all.
 *
 * V011 itself could not be taught the new column. It is applied on every environment that has
 * started since, and the runner compares an applied script's checksum and refuses to start on a
 * mismatch — which is exactly what editing it did. The script it wrote is what gets fixed instead,
 * here.
 *
 * ## What it will and will not touch
 *
 * Only a file at the store root named the way V011 names its script — `boards-seed.sql`, or
 * `boards-seed-<n>.sql` when that was taken — and whose header says V011 generated it. A script
 * seedgen wrote, or one an operator put there, is not V011's and is left alone.
 *
 * Within one, only the `INSERT INTO task` statements change, and each by the same two edits: the
 * column list gains `on_success_compact` after `on_success_mode`, and the statement's last line —
 * `<chat>, <next task>, '<mode>', '<rank>');`, which V011 always writes on a line of its own and which
 * no quoted text can imitate, a quote inside a literal being doubled — gains the box after the mode.
 * If the statements and their last lines do not pair up one for one, the file is not what this
 * migration was written against: it is left as it is and named, and its import fails loudly on the
 * check rather than quietly on something else.
 *
 * A script that already lists `on_success_compact` is done, so running this twice is a no-op.
 */

const fs = require('fs');
const path = require('path');
const { dataRoot } = require('./lib/kiao-fs');

const SEED_NAME = /^boards-seed(-\d+)?\.sql$/;
const GENERATED_BY = 'Generated by migrations/V011__workflow-boards-to-seed-sql.js';

const COLUMNS_BEFORE = 'conversation_id, on_success_task_id, on_success_mode, rank) VALUES';
const COLUMNS_AFTER = 'conversation_id, on_success_task_id, on_success_mode, on_success_compact, rank) VALUES';

// The last line of a task INSERT: the next task (a uuid or NULL), the mode, the rank.
const TAIL = /(NULL|'[0-9a-fA-F-]{36}'::uuid), '(continue|compact|end)', ('[^']*')\);$/gm;

const count = (text, needle) => text.split(needle).length - 1;

/**
 * The script rewritten, with how many cards it holds and how many said `compact` — or null when it
 * is not one this migration can rewrite safely.
 */
function rewrite(script) {
    const cards = count(script, COLUMNS_BEFORE);
    if (cards !== [...script.matchAll(TAIL)].length) return null;
    let compact = 0;
    const out = script
        .split(COLUMNS_BEFORE).join(COLUMNS_AFTER)
        .replace(TAIL, (_, next, mode, rank) => {
            if (mode !== 'compact') return `${next}, '${mode}', false, ${rank});`;
            compact++;
            return `${next}, 'continue', true, ${rank});`;
        });
    return { out, cards, compact };
}

function main() {
    const root = dataRoot();
    console.log(`V012: bringing V011's boards scripts in ${root} to the compaction box`);

    let changed = 0;
    let refused = 0;
    for (const name of fs.readdirSync(root).filter((n) => SEED_NAME.test(n)).sort()) {
        const file = path.join(root, name);
        if (!fs.statSync(file).isFile()) continue;
        const script = fs.readFileSync(file, 'utf8');
        if (!script.includes(GENERATED_BY)) {
            console.log(`  ${name}: not written by V011 — left alone`);
            continue;
        }
        if (script.includes(COLUMNS_AFTER) || !script.includes(COLUMNS_BEFORE)) continue;

        const done = rewrite(script);
        if (done === null) {
            console.log(`  ${name}: its task statements are not the shape V011 writes — left as it is`);
            refused++;
            continue;
        }
        fs.writeFileSync(file, done.out, 'utf8');
        console.log(`  ${name}: ${done.cards} card(s), ${done.compact} of them compacted`);
        changed++;
    }

    console.log(`V012: done — ${changed} script(s) rewritten, ${refused} left as they were.`);
}

main();
