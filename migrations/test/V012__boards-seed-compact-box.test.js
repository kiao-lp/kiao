/**
 * Tests for V012__boards-seed-compact-box.js.
 *
 *     node --test "migrations/test/V012*.test.js"
 *
 * The input is V011's own golden script, and the expected output is what V011 was briefly edited to
 * write before its checksum stopped every environment that had run it: V012 has to arrive at exactly
 * that, byte for byte, from the script the frozen V011 still writes.
 *
 * It lives in this subdirectory because the runner discovers `V<NNN>__<name>.js` in the folder
 * above and would run a test file against the real store.
 */

const test = require('node:test');
const assert = require('node:assert');
const { spawnSync } = require('node:child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');

const MIGRATION = path.join(__dirname, '..', 'V012__boards-seed-compact-box.js');
const V011_SCRIPT = path.join(__dirname, 'boards-seed-v011.expected.sql');
const EXPECTED = path.join(__dirname, 'boards-seed-v012.expected.sql');

function newStore() {
    return fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'kiao-v012-')));
}

function run(root) {
    const res = spawnSync(process.execPath, [MIGRATION, root], { cwd: root, encoding: 'utf8' });
    assert.strictEqual(res.status, 0, `migration exited ${res.status}: ${res.stderr}`);
    return res.stdout + res.stderr;
}

const read = (file) => fs.readFileSync(file, 'utf8');

test('rewrites a V011 script to the columns schema V005 has, and a second run changes nothing', () => {
    const root = newStore();
    const script = path.join(root, 'boards-seed.sql');
    fs.copyFileSync(V011_SCRIPT, script);

    const out = run(root);
    assert.strictEqual(read(script), read(EXPECTED));
    assert.match(out, /12 card\(s\), 1 of them compacted/);

    run(root);
    assert.strictEqual(read(script), read(EXPECTED));
});

test('a numbered script is V011\'s too', () => {
    const root = newStore();
    const script = path.join(root, 'boards-seed-2.sql');
    fs.copyFileSync(V011_SCRIPT, script);
    run(root);
    assert.strictEqual(read(script), read(EXPECTED));
});

test('a script V011 did not write is left alone', () => {
    const root = newStore();
    const script = path.join(root, 'boards-seed.sql');
    const foreign = read(V011_SCRIPT).replace('Generated by migrations/V011__workflow-boards-to-seed-sql.js', 'Hand-written');
    fs.writeFileSync(script, foreign, 'utf8');
    assert.match(run(root), /not written by V011/);
    assert.strictEqual(read(script), foreign);
});

test('a script whose statements do not pair with their last lines is left as it is', () => {
    const root = newStore();
    const script = path.join(root, 'boards-seed.sql');
    const damaged = read(V011_SCRIPT).replace("'compact', 'i');", "'compact', 'i') ;");
    fs.writeFileSync(script, damaged, 'utf8');
    assert.match(run(root), /not the shape V011 writes/);
    assert.strictEqual(read(script), damaged);
});

test('a store without a script is a no-op', () => {
    const root = newStore();
    assert.match(run(root), /0 script\(s\) rewritten/);
    assert.deepStrictEqual(fs.readdirSync(root), []);
});
